// Generates web/src/api/contract.schema.json and contract.d.ts from the
// backend's Pydantic contract. Run with `npm run gen:contract`. Commit both
// outputs; re-running must not change them.
import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const web = resolve(here, '..')
const out = resolve(web, 'src/api')

const json = execFileSync(
  'uv',
  ['run', '--project', resolve(web, '../api'), 'python', resolve(here, 'contract_schema.py')],
  { cwd: web, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
)
const schema = JSON.parse(json)

// Pydantic puts a title on every property, which makes the generator emit
// numbered aliases such as Channel6. Keep titles on the named definitions only,
// so properties use the named types and plain inline types.
const strip = (node) => {
  if (Array.isArray(node)) return node.forEach(strip)
  if (node && typeof node === 'object') {
    delete node.title
    Object.values(node).forEach(strip)
  }
}
for (const def of Object.values(schema.$defs)) {
  const title = def.title
  strip(def)
  if (title) def.title = title
}

const banner = `/* eslint-disable */
/**
 * GENERATED by web/scripts/gen-contract.mjs from api/src/recheck/contract.
 * Do not edit by hand. Run \`npm run gen:contract\` after a backend change.
 */`

const ts = await compile(schema, 'Contract', {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  format: false,
  style: { singleQuote: true, semi: false },
})

mkdirSync(out, { recursive: true })
writeFileSync(resolve(out, 'contract.schema.json'), json.replace(/\r\n/g, '\n'))
writeFileSync(resolve(out, 'contract.d.ts'), ts.replace(/\r\n/g, '\n'))
console.log('wrote src/api/contract.schema.json and contract.d.ts')
